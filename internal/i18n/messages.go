package i18n

import "fmt"

// message 是一条界面文案。key 是稳定的标识，zh 是界面原文，en 是译文。
//
// 为什么从「中文原文当 key」改成命名 key：原文当 key 时，改一个字就等于换了一个
// key，译文会静默丢掉；同一个中文在不同地方意思不同（分栏 = Columns / Split）
// 也没有地方区分。命名 key 把「标识」和「文案」拆开，改文案不再动 key，
// 同一句中文在不同语境各有一条。
type message struct {
	zh string
	en string
}

// T 按 key 取当前语言的文案。
//
// 查不到就返回 key 本身：界面上冒出 "pdf.tool.prev_page" 很难看，但比空白好查——
// 一眼就能看出是哪个 key 漏了，而且测试会先拦下来（见 messages_test.go）。
func T(key string) string {
	m, ok := messages[key]
	if !ok {
		return key
	}
	if Language() == "en" {
		return m.en
	}
	return m.zh
}

// Tn 按数量选一条文案再填进去：n == 1 用 one，其余用 other。
//
// 不做 ngettext 就没有「复数形式」这一层，单复数靠两条完整的文案。中文两条通常写成
// 一样（中文没有单复数），英文一条 "1 document"、一条 "%d documents"。
// 只在实在绕不开数量的句子里用；能写成「标签: 数值」的地方还是那么写更省事。
func Tn(n int, one, other string, args ...any) string {
	key := other
	if n == 1 {
		key = one
	}
	return fmt.Sprintf(T(key), args...)
}

